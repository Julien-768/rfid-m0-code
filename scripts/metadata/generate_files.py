#!/usr/bin/env python3
"""Generate AUTHORS.md, CONTRIBUTORS.md and CITATION.cff from CodeMeta v3 metadata.

``codemeta.json`` is the single source of truth. The people logic (names,
identifiers, affiliations, roles, de-duplication) lives in ``codemeta_people.py``
so that the three generated files are always consistent.

Usage, from anywhere (the project root is the nearest folder above this script
that contains codemeta.json; the generated files are written there)::

    python3 generate_files.py

Nothing is written unless every file could be generated, and each file is
replaced atomically. Warnings about incomplete or inconsistent metadata go to
stderr and do not stop the generation; errors exit with status 1.
"""

import json
import os
import re
import sys
from datetime import date
from pathlib import Path
from urllib.parse import urlparse

import codemeta_people as cp
from codemeta_people import CodeMetaError, load_people, md_escape, md_link, sort_people


def find_root(start: Path) -> Path:
    """Return the project root: the nearest folder, from ``start`` upwards,
    that contains ``codemeta.json``. Falls back to ``start`` itself.

    This lets the scripts live in the root or in a sub-folder such as
    ``scripts/metadata/`` while AUTHORS.md & co. stay at the project root.
    """
    for folder in (start, *start.parents):
        if (folder / "codemeta.json").is_file():
            return folder
    return start


ROOT = find_root(Path(__file__).resolve().parent)
CODEMETA_FILE = ROOT / "codemeta.json"
AUTHORS_FILE = ROOT / "AUTHORS.md"
CONTRIBUTORS_FILE = ROOT / "CONTRIBUTORS.md"
CITATION_FILE = ROOT / "CITATION.cff"

GENERATED_NOTICE = (
    "<!-- Generated from codemeta.json by generate_files.py. "
    "Do not edit this file by hand. -->"
)
MISSING = "—"
NAME_NOT_PROVIDED = "Name not provided"


def yaml_string(value):
    """Serialize a string safely as a YAML double-quoted scalar."""
    return json.dumps(str(value), ensure_ascii=False)


def valid_iso_date(value):
    """Return an ISO date only if it is a real calendar date."""
    if not isinstance(value, str):
        return None

    try:
        parsed = date.fromisoformat(value)
    except ValueError:
        return None

    # Require YYYY-MM-DD, not a timestamp or another date representation.
    if parsed.isoformat() != value:
        return None

    return value


def get_license(metadata):
    """Extract an SPDX identifier from a license URL or string."""
    license_value = metadata.get("license")

    if not isinstance(license_value, str) or not license_value.strip():
        return None

    license_value = license_value.strip()
    parsed = urlparse(license_value)

    if parsed.scheme in ("http", "https"):
        identifier = parsed.path.rstrip("/").split("/")[-1]
    else:
        identifier = license_value

    # Avoid writing an arbitrary URL as if it were an SPDX identifier.
    if re.fullmatch(r"[A-Za-z0-9.+-]+", identifier):
        return identifier

    return None


def get_doi(metadata):
    """Return a DOI only when an actual DOI URL is supplied."""
    for key in ("doi", "identifier", "@id", "id"):
        value = metadata.get(key)

        if not isinstance(value, str):
            continue

        match = re.fullmatch(
            r"https?://(?:dx\.)?doi\.org/(10\.\d{4,9}/\S+)",
            value.strip(),
            re.IGNORECASE,
        )
        if match:
            return match.group(1)

    return None


# --------------------------------------------------------------------------- #
# Markdown rendering
# --------------------------------------------------------------------------- #


def identifier_links(person: cp.Person, orcid_label: str) -> list:
    """Markdown for the person's identifiers: the ORCID if any, else the
    identifier used in the metadata (@id, or the ``contributor``/``author``
    value of the Role objects that designate the person, e.g. an e-mail).
    """
    links = []
    if person.orcid_url:
        links.append(md_link(orcid_label.format(id=person.orcid), person.orcid_url))
    # md_link() makes http(s) URLs clickable and escapes anything else as text.
    links.extend(md_link(text, text) for text in cp.display_identifiers(person))
    return links


def build_authors_markdown(people: cp.People) -> str:
    """Render AUTHORS.md: the principal authors, in declaration order."""
    lines = [GENERATED_NOTICE, "", "# Authors", ""]

    if not people.authors:
        lines.append("No authors are declared in `codemeta.json`.")
    for person in people.authors:
        name = md_escape(person.name) if person.name else NAME_NOT_PROVIDED
        heading = f"- **{name}**"
        links = identifier_links(person, "ORCID")
        if links:
            heading += f" ({', '.join(links)})"
        lines.append(heading)
        for affiliation in person.affiliations:
            lines.append(f"  - Affiliation: {md_escape(affiliation)}")
        if person.roles:
            roles = ", ".join(md_escape(role) for role in person.roles)
            lines.append(f"  - Role: {roles}")
        lines.append("")

    if lines[-1] == "":
        lines.pop()
    lines += [
        "",
        "Other contributors are listed in [CONTRIBUTORS.md](CONTRIBUTORS.md).",
    ]
    return "\n".join(lines) + "\n"


def build_contributors_markdown(people: cp.People) -> str:
    """Render CONTRIBUTORS.md: contributors who are not authors, sorted by name."""
    lines = [GENERATED_NOTICE, "", "# Contributors", ""]

    if not people.contributors:
        lines.append("No additional contributors are declared in `codemeta.json`.")
        return "\n".join(lines) + "\n"

    lines += [
        "People who contributed to this software and are not listed as principal "
        "authors in [AUTHORS.md](AUTHORS.md).",
        "",
        "| Contributor | Identifier | Affiliation | Role |",
        "|---|---|---|---|",
    ]
    for person in sort_people(people.contributors):
        name = md_escape(person.name) if person.name else NAME_NOT_PROVIDED
        identifiers = "<br>".join(identifier_links(person, "ORCID: {id}")) or MISSING
        affiliations = "<br>".join(md_escape(a) for a in person.affiliations)
        roles = ", ".join(md_escape(role) for role in person.roles)
        lines.append(
            f"| {name} | {identifiers} | {affiliations or MISSING} | "
            f"{roles or MISSING} |"
        )
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# CITATION.cff
# --------------------------------------------------------------------------- #


def build_citation_text(metadata: dict, people: cp.People) -> str:
    """Build a Citation File Format (CFF) 1.2.0 document from the authors."""
    if not people.authors:
        raise ValueError(
            "No Person entries found in CodeMeta 'author'; "
            "cannot generate a valid citation."
        )

    name = metadata.get("name")
    if not isinstance(name, str) or not name.strip():
        raise ValueError("Missing required CodeMeta field: name")

    lines = [
        "cff-version: 1.2.0",
        "message: "
        + yaml_string("If you use this software, please cite it as follows."),
        "title: " + yaml_string(name),
        "authors:",
    ]

    for person in people.authors:
        author_lines = []

        if person.given:
            author_lines.append("  - given-names: " + yaml_string(person.given))
        else:
            author_lines.append("  -")

        if person.family:
            author_lines.append("    family-names: " + yaml_string(person.family))

        if person.orcid_url:
            author_lines.append("    orcid: " + yaml_string(person.orcid_url))
        if person.affiliations:
            affiliation = "; ".join(person.affiliations)
            author_lines.append("    affiliation: " + yaml_string(affiliation))

        lines.extend(author_lines)

    version = metadata.get("version")
    if isinstance(version, str) and version.strip():
        lines.append("version: " + yaml_string(version))

    released = valid_iso_date(metadata.get("datePublished"))
    if released:
        lines.append("date-released: " + yaml_string(released))
    elif metadata.get("datePublished"):
        print(
            "WARNING: datePublished is not a valid YYYY-MM-DD date; "
            "date-released omitted.",
            file=sys.stderr,
        )

    license_id = get_license(metadata)
    if license_id:
        lines.append("license: " + yaml_string(license_id))

    doi = get_doi(metadata)
    if doi:
        lines.append("doi: " + yaml_string(doi))

    repository = metadata.get("codeRepository")
    if isinstance(repository, str) and repository.strip():
        lines.append("repository-code: " + yaml_string(repository))

    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# File handling
# --------------------------------------------------------------------------- #


def load_metadata(path: Path = CODEMETA_FILE) -> dict:
    """Read and validate the CodeMeta file, with explicit error messages."""
    try:
        # utf-8-sig tolerates the BOM that some Windows editors add.
        with path.open("r", encoding="utf-8-sig") as file:
            metadata = json.load(file)
    except FileNotFoundError:
        raise CodeMetaError(f"CodeMeta file not found: {path}") from None
    except json.JSONDecodeError as error:
        raise CodeMetaError(
            f"Invalid JSON in {path}: {error.msg} "
            f"(line {error.lineno}, column {error.colno})."
        ) from error
    except UnicodeDecodeError as error:
        raise CodeMetaError(f"{path} is not valid UTF-8 text: {error}") from error

    if not isinstance(metadata, dict):
        raise CodeMetaError(f"{path}: the CodeMeta document must be a JSON object.")
    return metadata


def write_text(path: Path, content: str) -> None:
    """Write ``content`` (UTF-8, LF line endings) by replacing ``path`` atomically."""
    temporary = path.with_name(path.name + ".tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as file:
            file.write(content)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def generate_authors_file(metadata, output_file=AUTHORS_FILE, people=None):
    """Generate AUTHORS.md from CodeMeta ``author``."""
    people = people or load_people(metadata)
    write_text(output_file, build_authors_markdown(people))


def generate_contributors_file(metadata, output_file=CONTRIBUTORS_FILE, people=None):
    """Generate CONTRIBUTORS.md from CodeMeta ``contributor``."""
    people = people or load_people(metadata)
    write_text(output_file, build_contributors_markdown(people))


def generate_citation_file(metadata, output_file=CITATION_FILE, people=None):
    """Generate a Citation File Format (CFF) 1.2.0 file."""
    people = people or load_people(metadata)
    write_text(output_file, build_citation_text(metadata, people))


def generate_all(
    codemeta_file=CODEMETA_FILE,
    authors_file=AUTHORS_FILE,
    contributors_file=CONTRIBUTORS_FILE,
    citation_file=CITATION_FILE,
):
    """Generate every file, or none of them if anything fails.

    Returns the list of metadata warnings that were reported on stderr.
    """
    metadata = load_metadata(codemeta_file)
    people = load_people(metadata)

    # Build everything first so that a failure never leaves a half-updated set.
    outputs = (
        (authors_file, build_authors_markdown(people)),
        (contributors_file, build_contributors_markdown(people)),
        (citation_file, build_citation_text(metadata, people)),
    )

    for issue in people.issues:
        print(f"WARNING: {issue}", file=sys.stderr)
    for path, content in outputs:
        write_text(path, content)
    return people.issues


def main():
    try:
        generate_all()
    except (OSError, ValueError) as error:  # CodeMetaError is a ValueError
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)

    print(
        f"Generated {AUTHORS_FILE.name}, {CONTRIBUTORS_FILE.name} "
        f"and {CITATION_FILE.name}."
    )


if __name__ == "__main__":
    main()
